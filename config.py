import os


def get_secret_key():
    secret_key = os.environ.get("NOTICEBOARD_SECRET_KEY")
    if not secret_key:
        raise RuntimeError(
            "Set the NOTICEBOARD_SECRET_KEY environment variable before starting the app."
        )
    return secret_key


